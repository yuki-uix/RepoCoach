/**
 * Benchmark definitions — the pinned real-repository cost comparisons in
 * `fixtures/benchmarks/real-repos.json`.
 *
 * Each entry pins the repository to a commit SHA and the feature to a fixed
 * (featureId, featureGoal, entryFiles) triple plus scripted learner answers, so
 * N runs of the same benchmark explore the same code path every time. That is
 * what makes a before/after comparison mean anything: without the pin, the
 * model picks a different candidate each run and the token totals are not
 * comparable (the #37 measurement's exact failure mode).
 *
 * The file is re-validated through zod before anything trusts it — a malformed
 * entry fails loudly, never silently downgrades to a shorter answer list or a
 * missing entry-file set.
 */

import { readFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { formatZodError } from "../agent/errors.js";

const FULL_SHA_RE = /^[0-9a-f]{40}$/;

export const benchmarkSchema = z.object({
  name: z.string().min(1),
  /** `<url>#<sha>` for a remote repo, or a local path (tests use fixture repos). */
  repositoryId: z.string().min(1),
  featureId: z.string().min(1),
  featureGoal: z.string().min(1),
  /** Pinned entry files — the candidate is not regenerated by the model. */
  entryFiles: z.array(z.string().min(1)).min(1),
  /** Scripted learner answers, consumed in order across the session. */
  answers: z.array(z.string().min(1)).min(1),
});
export type Benchmark = z.infer<typeof benchmarkSchema>;

export const benchmarksFileSchema = z
  .array(benchmarkSchema)
  .min(1)
  .superRefine((benchmarks, ctx) => {
    const seenNames = new Set<string>();
    for (let index = 0; index < benchmarks.length; index++) {
      const benchmark = benchmarks[index]!;
      if (seenNames.has(benchmark.name)) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: [index, "name"],
          message: `duplicate benchmark name "${benchmark.name}"`,
        });
      }
      seenNames.add(benchmark.name);
      // A remote benchmark without a pinned SHA is not repeatable: the reader
      // would clone whatever the default branch points at today. Local paths
      // (tests) are exempt — they pin nothing because nothing is fetched.
      if (isRemoteUrl(benchmark.repositoryId) && pinnedSha(benchmark.repositoryId) === undefined) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          path: [index, "repositoryId"],
          message: "remote repositoryId must pin a full 40-char commit SHA as `<url>#<sha>`",
        });
      }
    }
  });

/** Whether a repository id names a remote clone URL rather than a local path. */
function isRemoteUrl(repositoryId: string): boolean {
  return /^[a-z][a-z0-9+.-]*:\/\//i.test(repositoryId) || repositoryId.startsWith("git@");
}

/** The 40-char SHA a `url#sha` id pins, or undefined when it pins none. */
function pinnedSha(repositoryId: string): string | undefined {
  const hash = repositoryId.lastIndexOf("#");
  if (hash === -1) return undefined;
  const candidate = repositoryId.slice(hash + 1);
  return FULL_SHA_RE.test(candidate) ? candidate : undefined;
}

/**
 * Read + validate `fixtures/benchmarks/real-repos.json`, returning every
 * benchmark (or the single one named by `name`). Throws with the file path and
 * the zod issue list on any parse or validation failure.
 */
export function loadBenchmarks(repoRoot: string, name?: string): Benchmark[] {
  const path = join(repoRoot, "fixtures", "benchmarks", "real-repos.json");
  let raw: string;
  try {
    raw = readFileSync(path, "utf8");
  } catch (error) {
    throw new Error(
      `Missing benchmarks file ${path}: ${error instanceof Error ? error.message : String(error)}`,
      { cause: error },
    );
  }
  let parsed: unknown;
  try {
    parsed = JSON.parse(raw);
  } catch (error) {
    throw new Error(
      `Invalid JSON in ${path}: ${error instanceof Error ? error.message : String(error)}`,
      { cause: error },
    );
  }
  const result = benchmarksFileSchema.safeParse(parsed);
  if (!result.success) {
    throw new Error(`Invalid benchmarks file ${path}: ${formatZodError(result.error)}`);
  }
  if (name === undefined) {
    return result.data;
  }
  const found = result.data.filter((benchmark) => benchmark.name === name);
  if (found.length === 0) {
    throw new Error(`No benchmark named "${name}" in ${path}`);
  }
  return found;
}
